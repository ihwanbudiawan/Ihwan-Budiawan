export function exportAnomaliesToExcel(records: AMRRecord[], fileName = 'LAPORAN_AUDIT_ANOMALI_AMR.xlsx'): void {
  const exportRows = records.map((rec, idx) => {
    const anomalyTitles = rec.anomalies.map(a => `[${a.severity.toUpperCase()}] ${a.title}`).join(' | ');
    const recommendations = rec.anomalies.map(a => a.recommendation).join(' ; ');

    return {
      NO: idx + 1,
      IDPEL: rec.locationCode,
      NAMA_PELANGGAN: rec.namaPelanggan,
      MERK_METER: rec.merkMeter,
      TIPE_METER: rec.typeMeter,
      TARIF: rec.tariff,
      DAYA_VA: rec.power,
      SKOR_KESEHATAN: `${rec.healthScore}%`,
      STATUS: rec.healthScore >= 90 ? 'SEHAT' : rec.healthScore >= 70 ? 'PERINGATAN' : 'KRITIS',
      JUMLAH_ANOMALI: rec.anomalies.length,
      RINGKASAN_ANOMALI: anomalyTitles || 'Normal (Tidak ada anomali)',
      REKOMENDASI_TINDAKAN: recommendations || 'Kondisi instalasi meter normal, pertahankan pemeliharaan berkala.',
      TEGANGAN_VR: rec.voltageL1,
      TEGANGAN_VS: rec.voltageL2,
      TEGANGAN_VT: rec.voltageL3,
      ARUS_IR: rec.currentL1,
      ARUS_IS: rec.currentL2,
      ARUS_IT: rec.currentL3,
      ARUS_NETRAL: rec.currentN,
      COSPHI_TOTAL: rec.powerFactorTotal,
      DAYA_METER_SEKUNDER_WATT: rec.activePowerTotal,
      FAKTOR_KALI_FK: rec.multiplier,
      PEMAKAIAN_AKTUAL_KW: Number(rec.actualPowerKw.toFixed(2)),
      RUMUS_PEMAKAIAN: `(${rec.activePowerTotal} W / 1000) * ${rec.multiplier} = ${rec.actualPowerKw.toFixed(2)} kW`,
      DAYA_AKTIF_P1_W: rec.activePowerL1,
      DAYA_AKTIF_P2_W: rec.activePowerL2,
      DAYA_AKTIF_P3_W: rec.activePowerL3,
      DAYA_REAKTIF_TOTAL_VAR: rec.reactivePowerTotal,
      STAND_KWH_TOTAL: rec.kwhImportTotal ?? 0,
      WAKTU_BACA: rec.readDate,
      ULP: rec.namaUp || 'KUDUS KOTA',
      UP3: rec.namaAp || 'KUDUS'
    };
  });

  const wb = XLSX.utils.book_new();
  const ws = XLSX.utils.json_to_sheet(exportRows);
  XLSX.utils.book_append_sheet(wb, ws, 'HASIL_DIAGNOSTIK');

  XLSX.writeFile(wb, fileName);
}
